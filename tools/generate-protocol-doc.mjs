import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const contract = JSON.parse(readFileSync(join(root, 'bridge', 'protocol-contract.json'), 'utf8'))
const bullets = (items) => items.map((item) => `- \`${item}\``).join('\n')
const markdown = `<!-- Generated by tools/generate-protocol-doc.mjs from bridge/protocol-contract.json. -->
# DSH TUI Wire Protocol

Canonical machine-readable source: [\`bridge/protocol-contract.json\`](../bridge/protocol-contract.json).
Do not edit capacities or message rosters here by hand.

## Version and limits

| Field | Value |
|---|---:|
| Protocol version | ${contract.protocolVersion} |
| Snapshot surface events | ${contract.limits.snapshotEvents} |
| History page events | ${contract.limits.historyEvents} |
| Maximum normal frame | ${contract.limits.maxFrameBytes} bytes |
| Client replay guard | ${contract.limits.clientReplayEvents} events |

## Client → bridge messages

${bullets(contract.clientMessages)}

## Bridge → client messages

${bullets(contract.serverMessages)}

## Snapshot surface events

${bullets(contract.surfaceEvents)}

The client sends \`hello.protocolVersion\`; \`welcome\` replies with
\`protocolVersion\`, \`maxFrameBytes\`, and the attached session's authoritative
optional \`mode\` (latest committed selection, otherwise its creation header).
Older peers may omit these fields. A legacy bridge that emits larger frames requires an explicit
\`DSHE_LEGACY_MAX_FRAME_MB\` client override.
`
writeFileSync(join(root, 'docs', 'protocol.md'), markdown, 'utf8')
